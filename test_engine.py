def فحص(اسم, شرط, تفاصيل=""):
    global _passed, _failed
    حالة = "✅" if شرط else "❌"
    if شرط:
        _passed += 1
    else:
        _failed += 1
    print(f"{حالة} {اسم}" + (f"  | {تفاصيل}" if تفاصيل else ""))


def قريب(a, b, tol=REL):
    return math.isclose(a, b, rel_tol=tol, abs_tol=1e-6)


# 1) الإيراد النفطي — إعادة حساب مستقلة
def test_oil_revenue():
    سعر, fx = 60, 1310
    صافي = (4.1 - 0.8) * 1.0          # مليون برميل/يوم
    براميل = صافي * 1_000_000 * 365
    متوقع = (سعر * براميل * fx) / 1e9  # مليار دينار
    فعلي = حساب_الايرادات_النفطية(سعر, fx, P)
    فحص("الإيراد النفطي يطابق الحساب اليدوي", قريب(فعلي, متوقع),
        f"متوقع={متوقع:,.0f}  فعلي={فعلي:,.0f}")


# 2) هوية الرصيد = إجمالي الإيرادات − النفقات
def test_balance_identity():
    r = حساب_الموازنة(70, 1310, P)
    متوقع = r["إجمالي الإيرادات (مليار دينار)"] - r["النفقات (مليار دينار)"]
    فحص("الرصيد = إجمالي الإيرادات − النفقات", قريب(r["الرصيد (مليار دينار)"], متوقع),
        f"رصيد={r['الرصيد (مليار دينار)']:,.0f}")
    # إجمالي الإيرادات = نفطي + غير نفطي
    جمع = r["الإيرادات النفطية (مليار دينار)"] + r["الإيرادات غير النفطية (مليار دينار)"]
    فحص("إجمالي الإيرادات = نفطي + غير نفطي", قريب(r["إجمالي الإيرادات (مليار دينار)"], جمع))


# 3) الخطية: مضاعفة سعر النفط تضاعف الإيراد النفطي
def test_linearity_price():
    a = حساب_الايرادات_النفطية(50, 1310, P)
    b = حساب_الايرادات_النفطية(100, 1310, P)
    فحص("الإيراد النفطي خطي بسعر النفط (×2)", قريب(b, 2 * a),
        f"50$→{a:,.0f}  100$→{b:,.0f}")


# 4) التناسب مع سعر الصرف
def test_scaling_fx():
    a = حساب_الايرادات_النفطية(60, 1300, P)
    b = حساب_الايرادات_النفطية(60, 2600, P)
    فحص("الإيراد النفطي يتناسب مع سعر الصرف (×2)", قريب(b, 2 * a))


# 5) سعر نفط التعادل ⇒ رصيد ≈ صفر
def test_breakeven():
    m = ملخص_السيناريو(P, P.سعر_الصرف_الرسمي)
    سعر_تعادل = m["سعر نفط التعادل (دولار)"]
    رصيد = حساب_الموازنة(سعر_تعادل, P.سعر_الصرف_الرسمي, P)["الرصيد (مليار دينار)"]
    فحص("الرصيد عند سعر التعادل ≈ صفر", abs(رصيد) < 1.0,
        f"سعر التعادل={سعر_تعادل:,.2f}$  رصيد={رصيد:,.4f}")


# 6) اتجاه الاحتياطي: عجز يخفضه، فائض يرفعه
def test_reserve_direction():
    # سعر منخفض ⇒ عجز ⇒ احتياطي بعد < قبل
    عجز = حساب_الموازنة(40, 1310, P)
    فحص("العجز يخفض الاحتياطي",
        عجز["الرصيد (مليار دينار)"] < 0 and عجز["الاحتياطي بعد (مليار دينار)"] < P.الاحتياطيات_الاجنبية_مليار)
    # سعر مرتفع ⇒ فائض ⇒ احتياطي بعد > قبل
    فائض = حساب_الموازنة(140, 1310, P)
    فحص("الفائض يرفع الاحتياطي",
        فائض["الرصيد (مليار دينار)"] > 0 and فائض["الاحتياطي بعد (مليار دينار)"] > P.الاحتياطيات_الاجنبية_مليار)
    # مقدار تمويل المركزي = -الرصيد × النسبة
    متوقع_تمويل = -عجز["الرصيد (مليار دينار)"] * P.نسبة_تمويل_المركزي
    فحص("تمويل المركزي = -الرصيد × نسبة التمويل", قريب(عجز["تمويل المركزي (مليار دينار)"], متوقع_تمويل))


# 7) سدّ الفجوة 100% ⇒ السعر الرسمي الجديد = السعر الموازي
def test_gap_full_close():
    g = تحليل_الفجوة(P, 1.0, 70)
    فحص("سدّ 100% ⇒ السعر الرسمي الجديد = الموازي",
        قريب(g["السعر الرسمي الجديد"], P.سعر_الصرف_الموازي))
    # الرصيد بعد عند سدّ كامل = الرصيد المحسوب مباشرة عند السعر الموازي
    مباشر = حساب_الموازنة(70, P.سعر_الصرف_الموازي, P)["الرصيد (مليار دينار)"]
    فحص("الرصيد بعد السدّ الكامل = الرصيد عند السعر الموازي",
        قريب(g["الرصيد بعد (مليار دينار)"], مباشر))
    # سدّ 0% ⇒ لا تغيير
    g0 = تحليل_الفجوة(P, 0.0, 70)
    فحص("سدّ 0% ⇒ تحسّن الرصيد = صفر", قريب(g0["تحسن الرصيد (مليار دينار)"], 0.0, tol=1e-9))


# 8) التضخم المستورد — إعادة حساب مستقلة
def test_inflation():
    inf = تقدير_التضخم(P, 1310, 1500)
    نسبة_تغير = (1500 - 1310) / 1310
    متوقع = P.حصة_المستورد_من_السلة * P.معامل_تمرير_التضخم * نسبة_تغير * 100
    فحص("التضخم المستورد يطابق الصيغة", قريب(inf["التضخم المستورد التقديري %"], متوقع),
        f"متوقع={متوقع:.3f}%  فعلي={inf['التضخم المستورد التقديري %']:.3f}%")
    # زيادة فاتورة الاستيراد = الواردات × (سعر جديد − قديم)
    متوقع_فاتورة = P.واردات_سنوية_مليار_دولار * (1500 - 1310)
    فحص("زيادة فاتورة الاستيراد = الواردات × فرق الصرف",
        قريب(inf["زيادة فاتورة الاستيراد (مليار دينار)"], متوقع_فاتورة))


# 9) تحليل التخفيض: تحسّن الرصيد عن الأساس متسق
def test_devaluation_table():
    df = جدول_حسب_سعر_الصرف(P, 70)
    اساس = حساب_الموازنة(70, P.سعر_الصرف_الرسمي, P)["الرصيد (مليار دينار)"]
    for _, row in df.iterrows():
        متوقع = row["الرصيد (مليار دينار)"] - اساس
        if not قريب(row["تحسن الرصيد عن الأساس (مليار دينار)"], متوقع, tol=1e-9):
            فحص("عمود تحسّن الرصيد عن الأساس", False)
            return
    # التخفيض (سعر صرف أعلى) يحسّن الرصيد (إيراد نفطي أكبر بالدينار)
    مرتب = df.sort_values("سعر الصرف (دينار/دولار)")
    تصاعدي = all(
        x <= y + 1e-6 for x, y in zip(مرتب["الرصيد (مليار دينار)"], مرتب["الرصيد (مليار دينار)"][1:])
    )
    فحص("رفع سعر الصرف يحسّن الرصيد (اتجاه تصاعدي)", تصاعدي)


