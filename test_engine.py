# 11) خصم خام البصرة وكلفة الإنتاج
def test_basrah_discount_and_cost():
    P_cost = مدخلات(
        اسعار_النفط=[70],
        حجم_الصادرات_مليون_برميل_يوم=4.1,
        الاستهلاك_المحلي_مليون_برميل_يوم=0.8,
        حصة_الحكومة_من_الصادرات=1.0,
        ايام_السنة=365,
        سعر_الصرف_الرسمي=1310,
        سعر_الصرف_الموازي=1500,
        اسعار_الصرف_سيناريو=[1310],
        ايرادات_غير_نفطية_مليار=20000,
        اجمالي_النفقات_مليار=199000,
        النفقات_الجارية_مليار=150000,
        استخدام_الاجمالي=True,
        الاحتياطيات_الاجنبية_مليار=132000,
        النقد_القاعدي_مليار=104000,
        نسبة_تمويل_المركزي=0.3,
        نسبة_الفائض_للاحتياطي=0.5,
        خصم_خام_البصرة_دولار=3.0,
        كلفة_انتاج_البرميل_دولار=5.0,
    )
    # إيراد 70$ مع خصم 8$ يجب أن يطابق إيراد 62$ بدون خصم
    rev_with_deduction = حساب_الايرادات_النفطية(70, 1310, P_cost)
    rev_net = حساب_الايرادات_النفطية(62, 1310, P)
    فحص("خصم خام البصرة (3$) وكلفة الإنتاج (5$) تخفض السعر الصافي بدقة",
        قريب(rev_with_deduction, rev_net),
        f"مع الخصم={rev_with_deduction:,.0f}  صافي 62$={rev_net:,.0f}")

    # التحقق من أن سعر التعادل عند وجود خصم 8$ يزيد بمقدار 8$ بالضبط
    m_base = ملخص_السيناريو(P, 1310)
    m_cost = ملخص_السيناريو(P_cost, 1310)
    فارق_التعادل = m_cost["سعر نفط التعادل (دولار)"] - m_base["سعر نفط التعادل (دولار)"]
    فحص("سعر التعادل يزيد بمقدار مجموع الخصومات والتكاليف (8$)", قريب(فارق_التعادل, 8.0),
        f"فارق التعادل={فارق_التعادل:.2f}$")


