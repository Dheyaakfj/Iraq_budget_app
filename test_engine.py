# 16) محاكاة مونت كارلو لمخاطر أسعار النفط (Monte Carlo)
def test_monte_carlo():
    mc = محاكاة_مونت_كارلو(P, سعر_اساس=70.0, عدد_المحاكاة=1000, تقلب_النفط=0.25, seed=42)
    فحص("احتمالية العجز تقع ضمن [0, 100]", 0.0 <= mc["احتمالية حدوث عجز %"] <= 100.0,
        f"احتمالية العجز={mc['احتمالية حدوث عجز %']}%")
    فحص("احتمالية كسر الاحتياطي تقع ضمن [0, 100]", 0.0 <= mc["احتمالية هبوط الاحتياطي دون M0 %"] <= 100.0,
        f"احتمالية كسر M0={mc['احتمالية هبوط الاحتياطي دون M0 %']}%")
    فحص("تسلسل الرتب المئوية منطقي: P10 <= P50 <= P90",
        mc["السيناريو المتشائم P10 (ترليون)"] <= mc["وسيط الرصيد المتوقع (ترليون)"] <= mc["السيناريو المتفائل P90 (ترليون)"],
        f"P10={mc['السيناريو المتشائم P10 (ترليون)']}  P50={mc['وسيط الرصيد المتوقع (ترليون)']}  P90={mc['السيناريو المتفائل P90 (ترليون)']}")
    فحص("مؤشر القيمة المعرضة للخطر (VaR 95%) أقل أو يساوي الوسيط",
        mc["أقصى عجز بمستوى ثقة 95% (VaR)"] <= mc["وسيط الرصيد المتوقع (ترليون)"],
        f"VaR 95%={mc['أقصى عجز بمستوى ثقة 95% (VaR)']} ترليون")
    فحص("عدد عينات المحاكاة يطابق المطلوب", len(mc["عينة_الارصدة"]) == 1000)


