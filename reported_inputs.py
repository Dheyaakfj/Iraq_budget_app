def supersedes(entry, official_period):
    """يتقدّم التصريح على قيمة البنك المركزي فقط إن كان شهره أحدث من فترة النشرة.

    عند صدور نشرة تغطي شهر القرار أو ما بعده تعود الأسبقية للرقم الرسمي المنشور فيها.
    """
    return entry['as_of'].strftime('%Y-%m') > str(official_period)


def age_days(entry, today=None):
    return ((today or date.today()) - entry['as_of']).days


def is_stale(entry, today=None):
    return age_days(entry, today) > STALE_AFTER_DAYS
