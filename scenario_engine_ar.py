# الملخص العام
# ----------------------------------------------------------------------
def ملخص_السيناريو(p: "مدخلات", سعر_الصرف: float) -> Dict[str, float]:
    df = جدول_حسب_سعر_النفط(p, سعر_الصرف)
    اسوأ = df.loc[df["الرصيد (مليار دينار)"].idxmin()]
    افضل = df.loc[df["الرصيد (مليار دينار)"].idxmax()]
    عند_اقل_سعر = df.loc[df["سعر النفط (دولار)"].idxmin()]

    # سعر النفط الذي يحقق التعادل (الرصيد = صفر) عند سعر الصرف الحالي
    صادرات = صافي_براميل_التصدير(p)
    براميل_سنوياً = صادرات * 1_000_000 * p.ايام_السنة
    الانفاق = p.اجمالي_النفقات_مليار if p.استخدام_الاجمالي else p.النفقات_الجارية_مليار
    مطلوب_من_النفط_مليار = الانفاق - p.ايرادات_غير_نفطية_مليار
    سعر_التعادل = None
    if براميل_سنوياً > 0 and سعر_الصرف > 0:
        صافي_تعادل = (مطلوب_من_النفط_مليار * 1e9) / (براميل_سنوياً * سعر_الصرف)
        سعر_التعادل = صافي_تعادل + p.خصم_خام_البصرة_دولار + p.كلفة_انتاج_البرميل_دولار

    # سعر تعادل الرواتب (Wage Breakeven Oil Price)
    # هو سعر النفط الأدنى لتغطية فاتورة الرواتب والتقاعد وشبكة الحماية الاجتماعية بعد مساهمة غير النفطي
    مطلوب_للرواتب_مليار = max(p.فاتورة_الرواتب_مليار - p.ايرادات_غير_نفطية_مليار, 0.0)
    سعر_تعادل_الرواتب = None
    if براميل_سنوياً > 0 and سعر_الصرف > 0:
        صافي_رواتب = (مطلوب_للرواتب_مليار * 1e9) / (براميل_سنوياً * سعر_الصرف)
        سعر_تعادل_الرواتب = صافي_رواتب + p.خصم_خام_البصرة_دولار + p.كلفة_انتاج_البرميل_دولار

    # سعر تعادل النفقات الجارية (Operational Breakeven Oil Price)
    مطلوب_للجاري_مليار = max(p.النفقات_الجارية_مليار - p.ايرادات_غير_نفطية_مليار, 0.0)
    سعر_تعادل_الجاري = None
    if براميل_سنوياً > 0 and سعر_الصرف > 0:
        صافي_جاري = (مطلوب_للجاري_مليار * 1e9) / (براميل_سنوياً * سعر_الصرف)
        سعر_تعادل_الجاري = صافي_جاري + p.خصم_خام_البصرة_دولار + p.كلفة_انتاج_البرميل_دولار

    return {
        "اسم السيناريو": p.اسم_السيناريو,
        "سعر الصرف المستخدم": سعر_الصرف,
        "أقل سعر نفط": float(df["سعر النفط (دولار)"].min()),
        "أعلى سعر نفط": float(df["سعر النفط (دولار)"].max()),
        "أكبر عجز (ترليون)": float(اسوأ["الرصيد (مليار دينار)"] / 1000.0),
        "أكبر فائض (ترليون)": float(افضل["الرصيد (مليار دينار)"] / 1000.0),
        "الاحتياطي عند أقل سعر (ترليون)": float(عند_اقل_سعر["الاحتياطي بعد (مليار دينار)"] / 1000.0),
        "الفجوة النقدية عند أقل سعر (ترليون)": float(عند_اقل_سعر["الفجوة النقدية (مليار دينار)"] / 1000.0),
        "سعر نفط التعادل (دولار)": (float(سعر_التعادل) if سعر_التعادل is not None else None),
        "سعر تعادل الرواتب (دولار)": (float(سعر_تعادل_الرواتب) if سعر_تعادل_الرواتب is not None else None),
        "سعر تعادل النفقات الجارية (دولار)": (float(سعر_تعادل_الجاري) if سعر_تعادل_الجاري is not None else None),
        "فاتورة الرواتب (مليار دينار)": p.فاتورة_الرواتب_مليار,
    }


