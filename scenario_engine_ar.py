def محاكاة_مونت_كارلو(
    p: "مدخلات",
    سعر_اساس: float = 70.0,
    عدد_المحاكاة: int = 2000,
    تقلب_النفط: float = 0.25,
    seed: int = 42,
) -> Dict[str, Any]:
    """
    محاكاة مونت كارلو الاحتمالية لمسارات أسعار النفط وأثرها على الموازنة والاحتياطيات.
    تقلب_النفط: الانحراف المعياري السنوي لأسعار النفط (افتراضياً 25%).
    عدد_المحاكاة: عدد المسارات المحاكاة (افتراضياً 2,000 مسار).
    """
    if seed is not None:
        random.seed(seed)

    اسعار_محاكاة = []
    ارصدة_محاكاة = []
    احتياطيات_محاكاة = []
    عجز_عدد = 0
    خطر_احتياطي_عدد = 0

    صادرات = صافي_براميل_التصدير(p)
    براميل_سنوياً = صادرات * 1_000_000 * p.ايام_السنة
    انفاق = p.اجمالي_النفقات_مليار if p.استخدام_الاجمالي else p.النفقات_الجارية_مليار
    غير_نفطي = p.ايرادات_غير_نفطية_مليار
    سعر_صرف = p.سعر_الصرف_الرسمي

    for _ in range(عدد_المحاكاة):
        z = random.gauss(0.0, 1.0)
        سعر = سعر_اساس * math.exp(-0.5 * (تقلب_النفط ** 2) + تقلب_النفط * z)
        سعر = max(15.0, min(180.0, سعر))

        سعر_صافي = max(سعر - p.خصم_خام_البصرة_دولار - p.كلفة_انتاج_البرميل_دولار, 0.0)
        ايراد_نفطي = (سعر_صافي * براميل_سنوياً * سعر_صرف) / 1e9
        اجمالي_ايراد = ايراد_نفطي + غير_نفطي
        رصيد = اجمالي_ايراد - انفاق

        if رصيد < 0:
            عجز_عدد += 1
            تمويل = -رصيد * p.نسبة_تمويل_المركزي
            احتياطي_بعد = p.الاحتياطيات_الاجنبية_مليار - تمويل
        else:
            فائض = رصيد * p.نسبة_الفائض_للاحتياطي
            احتياطي_بعد = p.الاحتياطيات_الاجنبية_مليار + فائض

        if احتياطي_بعد < p.النقد_القاعدي_مليار:
            خطر_احتياطي_عدد += 1

        اسعار_محاكاة.append(سعر)
        ارصدة_محاكاة.append(رصيد / 1000.0)
        احتياطيات_محاكاة.append(احتياطي_بعد / 1000.0)

    ارصدة_مرتبة = sorted(ارصدة_محاكاة)
    اسعار_مرتبة = sorted(اسعار_محاكاة)

    def percentile(lst, p_rank):
        k = (len(lst) - 1) * (p_rank / 100.0)
        f = math.floor(k)
        c = math.ceil(k)
        if f == c:
            return lst[int(k)]
        d0 = lst[int(f)] * (c - k)
        d1 = lst[int(c)] * (k - f)
        return d0 + d1

    احتمال_العجز = (عجز_عدد / عدد_المحاكاة) * 100.0
    احتمال_خطر_الاحتياطي = (خطر_احتياطي_عدد / عدد_المحاكاة) * 100.0
    var_95 = percentile(ارصدة_مرتبة, 5.0)

    return {
        "عدد المحاكاة": عدد_المحاكاة,
        "سعر النفط الأساس": سعر_اساس,
        "تقلب النفط %": تقلب_النفط * 100.0,
        "احتمالية حدوث عجز %": round(احتمال_العجز, 1),
        "احتمالية هبوط الاحتياطي دون M0 %": round(احتمال_خطر_الاحتياطي, 1),
        "متوسط الرصيد المتوقع (ترليون)": round(sum(ارصدة_محاكاة) / len(ارصدة_محاكاة), 1),
        "وسيط الرصيد المتوقع (ترليون)": round(percentile(ارصدة_مرتبة, 50.0), 1),
        "السيناريو المتفائل P90 (ترليون)": round(percentile(ارصدة_مرتبة, 90.0), 1),
        "السيناريو المتشائم P10 (ترليون)": round(percentile(ارصدة_مرتبة, 10.0), 1),
        "أقصى عجز بمستوى ثقة 95% (VaR)": round(var_95, 1),
        "متوسط سعر النفط المحاكى": round(sum(اسعار_محاكاة) / len(اسعار_محاكاة), 1),
        "أدنى سعر في المحاكاة": round(min(اسعار_محاكاة), 1),
        "أعلى سعر في المحاكاة": round(max(اسعار_محاكاة), 1),
        "عينة_الارصدة": [round(x, 1) for x in ارصدة_مرتبة],
        "عينة_الاسعار": [round(x, 1) for x in اسعار_مرتبة],
    }


def جلب_اسعار_النفط_الحية() -> Dict[str, Any]:
    """
    يجلب سعر خام برنت اللحظي وسعر سلة أوبك ونفط البصرة التقديري عبر واجهة عامة،
    مع وجود fallback آمن وفوري في حال انقطاع الاتصال أو بطء الشبكة.
    """
    نتيجة = {
        "متاح": False,
        "سعر_برنت": 72.50,
        "التغير": 0.0,
        "نسبة_التغير": 0.0,
        "سعر_البصرة_المتوسط_التقديري": 69.50,
        "المصدر": "القيم المرجعية (وضع عدم الاتصال)",
        "وقت_التحديث": "محدّث افتراضياً",
    }

    try:
        url = "https://query1.finance.yahoo.com/v8/finance/chart/BZ=F?interval=1d&range=1d"
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=1.8) as response:
            if response.status == 200:
                data = json.loads(response.read().decode("utf-8"))
                meta = data["chart"]["result"][0]["meta"]
                price = float(meta.get("regularMarketPrice", 72.50))
                prev = float(meta.get("chartPreviousClose", price))
                change = price - prev
                pct = (change / prev) * 100.0 if prev > 0 else 0.0
                نتيجة["متاح"] = True
                نتيجة["سعر_برنت"] = round(price, 2)
                نتيجة["التغير"] = round(change, 2)
                نتيجة["نسبة_التغير"] = round(pct, 2)
                نتيجة["سعر_البصرة_المتوسط_التقديري"] = round(max(price - 3.0, 0.0), 2)
                نتيجة["المصدر"] = "مباشر: بورصة لندن (ICE Brent)"
                نتيجة["وقت_التحديث"] = "بيانات السوق الحية اللحظية"
    except Exception:
        pass

    return نتيجة


