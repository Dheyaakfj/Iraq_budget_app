def حساب_مؤشر_الاستقرار(سعر_النفط: float, p: "مدخلات") -> Dict[str, Any]:
    """
    يحسب مؤشر الاستدامة المالية والنقدية المركب (من 0 إلى 100).
    يعتمد على 4 ركائز:
    1) وضع سعر النفط بالنسبة لسعر تعادل الموازنة وسعر تعادل الرواتب (40 نقطة).
    2) رصيد الموازنة نسبة إلى النفقات (20 نقطة).
    3) كفاية الاحتياطيات الأجنبية وتغطية النقد القاعدي M0 (25 نقطة).
    4) أشهر تغطية الاستيراد واستقرار سعر الصرف (15 نقطة).
    """
    row = حساب_الموازنة(سعر_النفط, p.سعر_الصرف_الرسمي, p)
    ملخص = ملخص_السيناريو(p, p.سعر_الصرف_الرسمي)
    سعر_تعادل = ملخص["سعر نفط التعادل (دولار)"] or 75.0
    سعر_رواتب = ملخص["سعر تعادل الرواتب (دولار)"] or 35.0

    # 1. ركيزة سعر النفط (40 نقطة)
    if سعر_النفط >= سعر_تعادل:
        نقاط_نفط = 40.0
    elif سعر_النفط <= سعر_رواتب:
        نقاط_نفط = max(0.0, (سعر_النفط / سعر_رواتب) * 15.0) if سعر_رواتب > 0 else 0.0
    else:
        مدى = max(سعر_تعادل - سعر_رواتب, 1.0)
        نسبة = (سعر_النفط - سعر_رواتب) / مدى
        نقاط_نفط = 15.0 + (نسبة * 25.0)

    # 2. ركيزة رصيد الموازنة (20 نقطة)
    رصيد = row["الرصيد (مليار دينار)"]
    نفقات = row["النفقات (مليار دينار)"]
    if رصيد >= 0:
        نقاط_رصيد = 20.0
    else:
        نسبة_عجز = abs(رصيد) / نفقات if نفقات > 0 else 0.5
        نقاط_رصيد = max(0.0, 20.0 * (1.0 - min(نسبة_عجز * 2.0, 1.0)))

    # 3. ركيزة الاحتياطي و M0 (25 نقطة)
    احتياطي = row["الاحتياطي بعد (مليار دينار)"]
    نقد = p.النقد_القاعدي_مليار
    نسبة_تغطية_m0 = (احتياطي / نقد) if نقد > 0 else 1.0
    if نسبة_تغطية_m0 >= 1.0:
        نقاط_احتياطي = 25.0
    elif نسبة_تغطية_m0 >= 0.7:
        نقاط_احتياطي = 10.0 + ((نسبة_تغطية_m0 - 0.7) / 0.3) * 15.0
    else:
        نقاط_احتياطي = max(0.0, (نسبة_تغطية_m0 / 0.7) * 10.0)

    # 4. ركيزة أشهر الاستيراد وفجوة الصرف (15 نقطة)
    احتياطي_دولار = (احتياطي * 1e9) / p.سعر_الصرف_الرسمي / 1e9 if p.سعر_الصرف_الرسمي > 0 else 0.0
    واردات_شهرية = p.واردات_سنوية_مليار_دولار / 12.0
    اشهر_استيراد = (احتياطي_دولار / واردات_شهرية) if واردات_شهرية > 0 else 0.0

    فجوة_صرف = (p.سعر_الصرف_الموازي - p.سعر_الصرف_الرسمي) / p.سعر_الصرف_الرسمي if p.سعر_الصرف_الرسمي > 0 else 0.0
    نقاط_استيراد = min(10.0, (اشهر_استيراد / 12.0) * 10.0)
    نقاط_فجوة = max(0.0, 5.0 * (1.0 - min(max(فجوة_صرف - 0.05, 0.0) / 0.15, 1.0)))
    نقاط_خارجية = نقاط_استيراد + نقاط_فجوة

    درجة_كلية = round(نقاط_نفط + نقاط_رصيد + نقاط_احتياطي + نقاط_خارجية, 1)
    درجة_كلية = max(0.0, min(100.0, درجة_كلية))

    if درجة_كلية >= 70.0:
        حالة = "منطقة أمان وراحة مالية"
        لون = "#0E6E5C"
        شرح = "الإيرادات والاحتياطيات في مستويات مريحة، والقدرة على تأمين الرواتب والنفقات مرتفعة."
    elif درجة_كلية >= 45.0:
        حالة = "منطقة حذر وضغط مالي متوسط"
        لون = "#C8A042"
        شرح = "هناك عجز مالي يمكن احتواؤه، والرواتب مؤمنة، لكن هبوطاً إضافياً في النفط سيبدأ باستنزاف الاحتياطيات."
    else:
        حالة = "منطقة خطر مالي وحرج"
        لون = "#C2392F"
        شرح = "ضغط مالي شديد؛ الإيرادات تقترب من العجز عن تغطية الرواتب وتتطلب سحباً حاداً من الاحتياطيات أو اقتراضاً واسعاً."

    return {
        "الدرجة": درجة_كلية,
        "الحالة": حالة,
        "اللون": لون,
        "الشرح": شرح,
        "نسبة تغطية M0 %": round(نسبة_تغطية_m0 * 100.0, 1),
        "أشهر تغطية الاستيراد": round(اشهر_استيراد, 1),
        "سعر تعادل الموازنة": round(سعر_تعادل, 1),
        "سعر تعادل الرواتب": round(سعر_رواتب, 1),
        "الرصيد (ترليون)": round(رصيد / 1000.0, 1),
    }


def توليد_بيانات_سانكي(سعر_النفط: float, p: "مدخلات") -> Dict[str, Any]:
    """
    تجهيز مصفوفة التدفق المالي (Sankey Flow) بالترليون دينار.
    يرسم دورة المال:
    الصادرات النفطية الإجمالية + غير النفطية -> إجمالي الموازنة -> (رواتب، تشغيلي، استثماري) + (فائض / عجز).
    """
    row = حساب_الموازنة(سعر_النفط, p.سعر_الصرف_الرسمي, p)
    صادرات_يومي = صافي_براميل_التصدير(p)
    براميل_سنوياً = صادرات_يومي * 1_000_000 * p.ايام_السنة

    صافي_نفطي_ترليون = row["الإيرادات النفطية (مليار دينار)"] / 1000.0
    غير_نفطي_ترليون = row["الإيرادات غير النفطية (مليار دينار)"] / 1000.0
    رواتب_ترليون = p.فاتورة_الرواتب_مليار / 1000.0
    نفقات_كلية_ترليون = row["النفقات (مليار دينار)"] / 1000.0

    نفقات_جارية_ترليون = p.النفقات_الجارية_مليار / 1000.0
    تشغيلي_اخر_ترليون = max(0.0, نفقات_جارية_ترليون - رواتب_ترليون)
    استثماري_ترليون = max(0.0, نفقات_كلية_ترليون - نفقات_جارية_ترليون) if p.استخدام_الاجمالي else 0.0

    كلف_تراخيص_ترليون = (p.كلفة_انتاج_البرميل_دولار * براميل_سنوياً * p.سعر_الصرف_الرسمي) / 1e12
    خصم_بصرة_ترليون = (p.خصم_خام_البصرة_دولار * براميل_سنوياً * p.سعر_الصرف_الرسمي) / 1e12
    اجمالي_نفط_ترليون = صافي_نفطي_ترليون + كلف_تراخيص_ترليون + خصم_بصرة_ترليون

    رصيد_ترليون = row["الرصيد (مليار دينار)"] / 1000.0

    labels = [
        "الصادرات النفطية الإجمالية",        # 0
        "الإيرادات غير النفطية",            # 1
        "صافي الإيراد النفطي للخزينة",      # 2
        "كلف الاستخراج والخصومات",          # 3
        "إجمالي الموازنة المتاحة",         # 4
        "فاتورة الرواتب والتقاعد",          # 5
        "النفقات التشغيلية والسلع",        # 6
        "المشاريع الاستثمارية والرأسمالية", # 7
        "فائض مالي (للاحتياطي)",           # 8
        "تمويل العجز (احتياطي / اقتراض)",  # 9
    ]

    source = []
    target = []
    value = []
    color = []

    # 1. النفط -> كلف التراخيص
    if (كلف_تراخيص_ترليون + خصم_بصرة_ترليون) > 0.05:
        source.append(0)
        target.append(3)
        value.append(round(كلف_تراخيص_ترليون + خصم_بصرة_ترليون, 2))
        color.append("rgba(194,57,47,0.35)")

    # 2. النفط -> صافي الخزينة
    source.append(0)
    target.append(2)
    value.append(round(صافي_نفطي_ترليون, 2))
    color.append("rgba(14,110,92,0.6)")

    # 3. الصافي وغير النفطي -> الموازنة
    source.append(2)
    target.append(4)
    value.append(round(صافي_نفطي_ترليون, 2))
    color.append("rgba(14,110,92,0.6)")

    if غير_نفطي_ترليون > 0:
        source.append(1)
        target.append(4)
        value.append(round(غير_نفطي_ترليون, 2))
        color.append("rgba(46,134,171,0.6)")

    # 4. إذا كان هناك عجز: يغذي الموازنة
    if رصيد_ترليون < 0:
        عجز_ترليون = abs(رصيد_ترليون)
        source.append(9)
        target.append(4)
        value.append(round(عجز_ترليون, 2))
        color.append("rgba(194,57,47,0.6)")

    # 5. الموازنة -> أوجه الصرف
    source.append(4)
    target.append(5)
    value.append(round(رواتب_ترليون, 2))
    color.append("rgba(200,160,66,0.7)")

    if تشغيلي_اخر_ترليون > 0:
        source.append(4)
        target.append(6)
        value.append(round(تشغيلي_اخر_ترليون, 2))
        color.append("rgba(107,124,120,0.6)")

    if استثماري_ترليون > 0:
        source.append(4)
        target.append(7)
        value.append(round(استثماري_ترليون, 2))
        color.append("rgba(46,134,171,0.7)")

    # 6. إذا كان هناك فائض: الموازنة -> الاحتياطي
    if رصيد_ترليون > 0:
        source.append(4)
        target.append(8)
        value.append(round(رصيد_ترليون, 2))
        color.append("rgba(14,110,92,0.8)")

    return {
        "labels": labels,
        "source": source,
        "target": target,
        "value": value,
        "color": color,
    }


